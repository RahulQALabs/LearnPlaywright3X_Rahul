//Both loops are brother and sister
//Keep initialisation outside, but it is not advisable

console.log("================ # For Loop # ==================");
let i = 0;
for (; i < 10; i++) {
    console.log(i);
}


console.log("================ # While Loop # ==================");
let j = 0;
while (j < 10) {
    console.log(j);
    j++;
}