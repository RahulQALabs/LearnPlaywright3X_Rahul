
// The loop variable name is flexible — you can use any name like index, i, or test


console.log("==================================");
for (let index = 0; index < 15; index++) {
    const element = index;
    console.log(element);
}

console.log("==================================");
for (let i = 1; i < 10; i++) {
    const element = i;
    console.log(element);
}

console.log("==================================");
for (let test = 0; test <= 10; test++) {
    const element = test;
    console.log(element);
}