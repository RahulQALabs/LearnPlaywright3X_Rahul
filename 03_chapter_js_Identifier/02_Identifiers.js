//Naming Covension Cases

//Camel Case - Suitable for variables and function names
let firstName = "Rahul";
let lastName = "Gupta";
console.log(firstName);
console.log(lastName);

function getFullName() {
    return "Hello! Rahul Gupta";
}

//Pascal Case - Suitable for class names and constructors
let RollNumber = 987;
console.log(RollNumber);


//snake case - Suitable for variable names and function names
let first_name = "Rahul";
let last_name = "Gupta";
console.log(first_name);
console.log(last_name);

//Screaming Snake Case - Suitable for constant names
const PI = 3.14;
console.log(PI);
const API_KEY="1234567890";
console.log(API_KEY);
const DB_URL="mongodb://localhost:27017/mydatabase";
console.log(DB_URL);

//Hungarian Notation - Suitable for variable names and function names
