// JavaScript Data Types
// 1. String - text values, e.g. "Hello"
// 2. Number - numeric values, e.g. 10, 3.14
// 3. Boolean - true or false
// 4. Undefined - variable declared but no value assigned
// 5. Null - represents no value
// 6. BigInt - large integers
// 7. Symbol - unique and immutable values
// 8. Object - collection of key-value pairs

//Reference Data Types or Non-Primitive Data Types
// 1. Object - collection of key-value pairs
// 2. Array - ordered list of values
// 3. Function - reusable block of code

// Example of Primitives Data Types
let name = "Rahul";
let age = 25;
let isStudent = true;
let city;
let emptyValue = null;

console.log(name);
console.log(age);
console.log(isStudent);
console.log(city);
console.log(emptyValue);

//Example of Reference Data Types
let person = {
    name: "Rahul",
    age: 35
}
console.log(person);


let numbers = [1, 2, 3, 4, 5];
console.log(numbers);


